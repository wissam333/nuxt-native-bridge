async function prompt(rl, question, fallback) {
  try {
    // At stdin EOF the pending question promise never settles (Node 24) —
    // race it against 'close' so scripted runs fall back instead of exiting.
    const answer = await Promise.race([
      rl.question(`${question}${fallback ? ` (${fallback})` : ''}: `),
      new Promise((_, reject) => rl.once('close', () => reject(new Error('stdin closed')))),
    ])
    return answer.trim() || fallback
  }
  catch {
    return fallback
  }
}

export async function init() {
  const appDir = process.cwd()
  const cfgFile = path.join(appDir, 'nuxt.config.ts')
  if (!fs.existsSync(cfgFile)) fail(`no nuxt.config.ts in ${appDir} — run inside the app directory`)

  // Step 1: config block (jiti read via readAppConfig; insertion on the text).
  const parsed = await readAppConfig(appDir)
  const pkg = JSON.parse(fs.readFileSync(path.join(appDir, 'package.json'), 'utf8'))
  const dirName = path.basename(appDir).replace(/[^a-z0-9]/gi, '')
  const rl = readline.createInterface({ input: process.stdin, output: process.stdout })
  const appId = await prompt(rl, 'Application id (reverse-DNS, permanent)', parsed.appId || pkg.appId || `com.example.${dirName.toLowerCase()}`)
  const appName = await prompt(rl, 'Application name', parsed.appName || pkg.displayName || dirName)
  rl.close()

  let configText = fs.readFileSync(cfgFile, 'utf8')
  configText = renderNuxtConfigPatch(configText, { id: appId, name: appName })
  fs.writeFileSync(cfgFile, configText)

  // Step 2: dependencies (workspace-local links until nnb publishes).
  const pkgFile = path.join(appDir, 'package.json')
  fs.writeFileSync(pkgFile, renderPackageJsonPatch(fs.readFileSync(pkgFile, 'utf8')))
  log('installing dependencies (pnpm if available, else npm)…')
  const hasPnpm = fs.existsSync(path.join(appDir, 'pnpm-lock.yaml'))
    || fs.existsSync(path.join(CLI_DIR, '..', '..', 'pnpm-lock.yaml'))
  if (hasPnpm && !fs.existsSync(path.join(appDir, 'pnpm-workspace.yaml'))) {
    // pnpm 12 fails the whole install when a native build script is unapproved
    // (esbuild via vite is hit by every Nuxt app; electron's binary download is
    // hit by the adapter), electron-packager cannot walk pnpm symlinks (T6), and
    // Forge's native-rebuild chain resolves via a git URL — mirror the monorepo
    // settings so standalone apps behave the same.
    fs.writeFileSync(path.join(appDir, 'pnpm-workspace.yaml'), `# nnb init: pnpm 12 build approvals + packaging layout for the electron adapter.
allowBuilds:
  esbuild: true
  "@parcel/watcher": true
  electron: true
  electron-winstaller: true
blockExoticSubdeps: false
nodeLinker: hoisted
`)
  }
  if (!fs.existsSync(path.join(appDir, '.npmrc'))) {
    // Persistent electron mirror + node-linker for Forge: forge's own pnpm
    // check reads .npmrc (not pnpm-workspace.yaml) and refuses symlinked
    // layouts — mirror the monorepo's committed .npmrc pair.
    fs.writeFileSync(path.join(appDir, '.npmrc'), `# nnb init: electron artifacts via mirror (GitHub CDN times out on restricted networks)
electron_mirror=https://npmmirror.com/mirrors/electron/
# electron-forge requires a hoisted (npm-like) layout when pnpm is used
node-linker=hoisted
`)
  }
  await run(hasPnpm ? 'pnpm' : 'npm', hasPnpm ? ['install'] : ['install', '--no-audit', '--no-fund'], { cwd: appDir, env: { ...process.env, ...electronEnv() } })

  // Step 3: capacitor.config.ts.
  const cfg = await readAppConfig(appDir)
  const brand = cfg.config.nativeBridge?.brand?.color || '#0D8A8F'
  const capFile = path.join(appDir, 'capacitor.config.ts')
  fs.writeFileSync(capFile, renderCapacitorConfig({ appId, appName, brand }))

  // Step 4: android shell when missing, then the native file sync.
  const androidDir = path.join(appDir, 'android')
  if (!fs.existsSync(androidDir)) {
    await run('npx', ['cap', 'add', 'android'], { cwd: appDir })
    const mainPath = path.join(androidDir, 'app', 'src', 'main', 'java', ...appId.split('.'), 'MainActivity.java')
    fs.writeFileSync(mainPath, renderMainActivity(appId))
    // Scaffold the bridge library INTO the app (self-contained Gradle — no
    // cross-install paths for npm consumers), then include the local copy.
    fs.cpSync(bridgeAndroidDir(), path.join(androidDir, 'nnb-bridge'), { recursive: true })
    const rel = 'nnb-bridge'
    const settingsFile = path.join(androidDir, 'settings.gradle')
    fs.writeFileSync(settingsFile, renderBridgeInclude(fs.readFileSync(settingsFile, 'utf8'), rel))
    const gradleFile = path.join(androidDir, 'app', 'build.gradle')
    fs.writeFileSync(gradleFile, renderAppGradlePatch(fs.readFileSync(gradleFile, 'utf8')))
    const wrapperFile = path.join(androidDir, 'gradle', 'wrapper', 'gradle-wrapper.properties')
    if (fs.existsSync(wrapperFile)) {
      fs.writeFileSync(wrapperFile, renderWrapperMirror(fs.readFileSync(wrapperFile, 'utf8')))
    }
  }
  nativeSync(appDir, cfg.config.nativeBridge)

  // local.properties: cap add only writes it when ANDROID_HOME is set (e2e
  // gate); reuse doctor's SDK detection so gradle always finds the SDK.
  const localProps = path.join(androidDir, 'local.properties')
  if (fs.existsSync(androidDir) && !fs.existsSync(localProps)) {
    const sdk = findSdk()
    if (sdk) {
      // properties format: escape backslash, then colon.
      fs.writeFileSync(localProps, `# generated by nnb init\nsdk.dir=${sdk.replace(/\\/g, '\\\\').replace(/:/g, '\\:')}\n`)
    }
    else {
      log('android/local.properties: no SDK found — set ANDROID_HOME so gradle can locate it')
    }
  }

  // Build-tools pin: AGP's default (35.0.0) is often missing from SDKs that
  // have the 36.x tools; idempotent for apps that pinned their own. (The
  // library-module override itself lives in root build.gradle via nnb sync.)
  const variablesFile = path.join(androidDir, 'variables.gradle')
  if (fs.existsSync(variablesFile)) {
    fs.writeFileSync(variablesFile, renderBuildToolsPin(fs.readFileSync(variablesFile, 'utf8')))
  }

  // Step 5: thin electron entry.
  fs.mkdirSync(path.join(appDir, 'electron'), { recursive: true })
  fs.writeFileSync(path.join(appDir, 'electron', 'main.cjs'), renderElectronMain(appName))

  // Step 6: icons when configured; doctor always.
  const icons = cfg.config.nativeBridge?.icons
  if (icons?.source) {
    const { icons: iconsCmd } = await import('./commands.mjs')
    await iconsCmd()
  }
  else {
    log('icons: nativeBridge.icons.source not configured — skipped')
  }
  const { doctor } = await import('./commands.mjs')
  await doctor()
  log('init complete — next: `nnb dev web` to verify, then `nnb build electron` / `nnb build android`')
}
