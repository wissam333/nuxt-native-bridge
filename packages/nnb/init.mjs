// Inserts the nativeBridge block (and the module registration) into
// nuxt.config.ts text. Existing nativeBridge blocks are left untouched.
export function renderNuxtConfigPatch(configText, { id, name }) {
  if (/nativeBridge:/.test(configText)) return configText

  const block = `  // nnb:init — generated by nnb init; edit freely. If you add your own
  // modules array, merge 'nuxt-native-bridge' into it.
  nativeBridge: {
    app: { id: '${id}', name: '${name}' },
    brand: { color: '#0D8A8F' },
    android: {
      splash: { hideOn: 'mounted', fade: 300, failsafe: 8000, light: '#0D8A8F', dark: '#0B1416' },
      mavenMirrors: ['https://maven.aliyun.com/repository/google', 'https://maven.aliyun.com/repository/central'],
      permissions: [],
    },
  },
  // /nnb:init`

  let out = configText
  // Existing modules array: append the module there (last-key-wins would
  // otherwise drop the app's own modules). Without one, the block brings it.
  const modules = /(modules:\s*\[)([^\]]*)(\])/.exec(out)
  if (modules) {
    const entries = modules[2].trim().replace(/,\s*$/, '')
    const joined = entries ? `${entries}, 'nuxt-native-bridge'` : `'nuxt-native-bridge'`
    out = out.replace(modules[0], `${modules[1]}${joined}${modules[3]}`)
  }
  // Insert before the final closer of defineNuxtConfig({ ... }).
  const closer = out.lastIndexOf('})')
  if (closer === -1) {
    throw new Error('could not find the defineNuxtConfig({...}) closer in nuxt.config.ts — wire nativeBridge manually')
  }
  const insert = modules ? block : `  modules: ['nuxt-native-bridge'],\n${block}\n`
  out = out.slice(0, closer) + `${insert}\n` + out.slice(closer)
  return out
}

export function renderCapacitorConfig({ appId, appName, brand }) {
  return `import type { CapacitorConfig } from '@capacitor/cli'

const config: CapacitorConfig = {
  appId: '${appId}',
  appName: '${appName}',
  webDir: '.output/public',
  plugins: {
    SplashScreen: {
      // The nnb module owns the splash hide (audit 19). The fade for the
      // INITIAL splash is launchFadeOutDuration — hide()'s fadeOutDuration
      // is ignored on Android (T9 device finding).
      launchAutoHide: false,
      launchFadeOutDuration: 300,
    },
  },
  android: {
    backgroundColor: '${brand}',
  },
}

export default config
`
}

export function renderMainActivity(appId) {
  return `package ${appId};

import com.nnb.bridge.NnbBridgeActivity;

/** Thin app shell (nnb): theme, edge-to-edge and insets live in the bridge library. */
public class MainActivity extends NnbBridgeActivity {
}
`
}

export function renderBridgeInclude(settingsText, relPath) {
  const wiring = `${BEGIN}
include ':nnb-bridge'
project(':nnb-bridge').projectDir = new File('${relPath}')
${END}`
  const marked = new RegExp(`${BEGIN.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}[\\s\\S]*?${END.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}`)
  if (marked.test(settingsText)) {
    return settingsText.replace(marked, wiring)
  }
  const at = settingsText.indexOf(`include ':app'`)
  if (at === -1) throw new Error('settings.gradle has no include \':app\' — wire :nnb-bridge manually')
  return settingsText.slice(0, at) + wiring + '\n\n' + settingsText.slice(at)
}

// app/build.gradle: implementation project(':nnb-bridge') between markers.
export function renderAppGradlePatch(gradleText) {
  const wiring = `    ${BEGIN}
    implementation project(':nnb-bridge')
    ${END}`
  const marked = new RegExp(`    ${BEGIN.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}[\\s\\S]*?    ${END.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}`)
  if (marked.test(gradleText)) return gradleText
  const at = gradleText.indexOf('dependencies {')
  if (at === -1) throw new Error('app/build.gradle has no dependencies block — wire :nnb-bridge manually')
  const open = at + 'dependencies {'.length
  return gradleText.slice(0, open) + `\n${wiring}` + gradleText.slice(open)
}

// cap 8's template leaves buildToolsVersion to AGP's default (35.0.0), which
// is absent from SDKs provisioned with the 36.x tools (T7 e2e gate); pin the
// coherent pair for compileSdk 36 (shortcut: hardcoded; revisit with cap 9).
export function renderBuildToolsPin(variablesText, version = '36.0.0') {
  if (/buildToolsVersion/.test(variablesText)) return variablesText
  const line = /^ {4}compileSdkVersion = .*$/m.exec(variablesText)
  if (!line) throw new Error('variables.gradle has no compileSdkVersion — pin buildToolsVersion manually')
  return variablesText.replace(line[0], `${line[0]}\n    buildToolsVersion = '${version}'`)
}

// Thin app-side electron entry: identity + UI dir env, then the adapter shell.
export function renderElectronMain(appName) {
  return `// Thin nnb electron entry (nnb init): env identity, then the hardened
// adapter shell. \`npx electron electron/\` runs the built UI from .output/public.
process.env.NNB_APP_NAME ||= ${JSON.stringify(appName)}
process.env.NNB_UI_DIR ||= require('node:path').join(__dirname, '..', '.output', 'public')
require('@nnb/adapter-electron/main.cjs')
`
}

// The capacitor template pins the gradle wrapper to services.gradle.org, which
// times out on restricted networks (found by the T7 e2e gate). Same file name,
// known-working mirror — swap only the host (shortcut: hardcoded default;
// promote to nativeBridge.android config when a second mirror is needed).
export function renderWrapperMirror(propsText) {
  const line = /^distributionUrl=(.*)$/m.exec(propsText)
  if (!line) return propsText
  // properties escape ':' in the template (https\://); normalize first.
  const url = line[1].trim().replace(/\\:/g, ':')
  const origin = 'https://services.gradle.org/distributions/'
  if (!url.startsWith(origin)) return propsText
  return propsText.replace(line[0], `distributionUrl=https://mirrors.cloud.tencent.com/gradle/${url.slice(origin.length)}`)
}

// Deps per plan T7 step 2: workspace-local until nnb publishes (Phase 3).
function renderPackageJsonPatch(pkgText) {
  const pkg = JSON.parse(pkgText)
  pkg.dependencies ||= {}
  pkg.devDependencies ||= {}
  for (const [name, version] of Object.entries({
    'nuxt-native-bridge': '^0.1.0',
    '@capacitor/core': '^8.0.0',
    // cap add android requires the android platform package too (plan T7's
    // list omits it — added here).
    '@capacitor/android': '^8.0.0',
    '@capacitor/app': '^8.0.0',
    '@capacitor/splash-screen': '^8.0.0',
    '@capacitor/status-bar': '^8.0.0',
  })) {
    if (!pkg.dependencies[name] && !pkg.devDependencies[name]) pkg.dependencies[name] = version
  }
  if (!pkg.devDependencies['@capacitor/cli']) pkg.devDependencies['@capacitor/cli'] = '^8.0.0'
  // nnb toolchain from npm: the CLI bin (nnb dev/build) + the hardened Electron
  // adapter (its electron/forge deps install with it, so `nnb build electron`
  // works from the app without the monorepo).
  if (!pkg.devDependencies['@nnb/cli']) pkg.devDependencies['@nnb/cli'] = '^0.1.0'
  if (!pkg.devDependencies['@nnb/adapter-electron']) pkg.devDependencies['@nnb/adapter-electron'] = '^0.1.0'
  // 2-space JSON, trailing newline — matches npm's own formatting.
  return `${JSON.stringify(pkg, null, 2)}\n`
}

