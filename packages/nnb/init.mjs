// `nnb init` — scaffolds a Nuxt app for all three targets (plan T7).
// Pure renderers are exported for tests; init() orchestrates prompts, file
// writes, installs and the cap/gradle wiring, then runs icons + doctor.
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import readline from 'node:readline/promises'
import { run, readAppConfig, fail, log, electronEnv, findSdk } from './lib.mjs'
import { nativeSync } from './native-sync.mjs'

const CLI_DIR = path.dirname(fileURLToPath(import.meta.url))

// Marker comment pair shared with the playground wiring (T1) so `nnb sync`
// keeps hands off and idempotency is uniform.
const BEGIN = '// nnb:bridge-library — generated wiring, rewritten by nnb init'
const END = '// /nnb:bridge-library'

// Vendored bridge-library source (copy of packages/adapter-capacitor/android).
// Scaffolded apps get an in-app copy so Gradle never reaches across installs;
// a node:test drift-guard keeps this copy in sync with the adapter original.
function bridgeAndroidDir() {
  return path.resolve(CLI_DIR, 'bridge-android')
}

