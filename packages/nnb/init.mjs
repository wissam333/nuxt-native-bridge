const LOGO_PLACEHOLDER = 'public/logo.png'

// A logo path is app-relative. Reject absolute paths, quotes and '..' so the
// value can be dropped into a single-quoted nuxt.config.ts string.
export function normalizeLogoPath(logo) {
  const normalized = String(logo ?? '').trim().replace(/\\/g, '/').replace(/^\.\//, '')
  if (!normalized || normalized.startsWith('/') || normalized.split('/').includes('..') || !/^[\w./-]+$/.test(normalized)) {
    return { error: `logo path must be a relative path inside the app, got ${JSON.stringify(logo)}` }
  }
  return { path: normalized }
}

// logo is set only when the file exists. A missing file keeps the typed path
// in the commented example instead of writing a block `nnb icons` cannot build.
export function resolveLogo(appDir, typed) {
  if (!typed) return { logo: null, commentedPath: null, note: null }
  const norm = normalizeLogoPath(typed)
  if (norm.error) return { logo: null, commentedPath: null, note: norm.error }
  const abs = path.join(appDir, norm.path)
  if (!fs.existsSync(abs) || !fs.statSync(abs).isFile()) {
    return { logo: null, commentedPath: norm.path, note: `logo not found: ${norm.path} — commented example uses that path` }
  }
  return { logo: norm.path, commentedPath: null, note: null }
}

export function hexColor(brand) {
  return /^#[0-9a-f]{6}$/i.test(brand || '') ? brand : '#0D8A8F'
}

// Live icons block, or the same block commented out. Markers let a later
// `nnb icons` replace the comment once a real logo path is given.
export function renderIconsLines(indent, { logo = null, brand = '#0D8A8F', commentedPath = null } = {}) {
  const color = hexColor(brand)
  const live = Boolean(logo)
  const iconPath = live ? logo : (commentedPath || LOGO_PLACEHOLDER)
  const slash = live ? '' : '// '
  const note = live
    ? 'generated by nnb. Edit the paths, then run `nnb icons`.'
    : 'point source, glyph and splash at your logo, then run `nnb icons`.'
  return [
    `${indent}// nnb:icons — ${note}`,
    `${indent}${slash}icons: {`,
    `${indent}${slash}  source: '${iconPath}',`,
    `${indent}${slash}  android: { glyph: '${iconPath}', background: '${color}' },`,
    `${indent}${slash}  splash: '${iconPath}',`,
    `${indent}${slash}},`,
    `${indent}// /nnb:icons`,
  ].join('\n') + '\n'
}

// Brace match that ignores strings and comments, so a commented icons example
// does not shift the nativeBridge closer.
function findNativeBridge(text) {
  const key = /nativeBridge\s*:/.exec(text)
  if (!key) return null
  let mode = 'code'
  let depth = 0
  let open = -1
  for (let i = key.index; i < text.length; i++) {
    const c = text[i]
    const n = text[i + 1]
    if (mode === 'line') {
      if (c === '\n') mode = 'code'
      continue
    }
    if (mode === 'block') {
      if (c === '*' && n === '/') {
        mode = 'code'
        i++
      }
      continue
    }
    if (mode === 's' || mode === 'd' || mode === 't') {
      const q = mode === 's' ? '\'' : mode === 'd' ? '"' : '`'
      if (c === '\\') {
        i++
        continue
      }
      if (c === q) mode = 'code'
      continue
    }
    if (c === '/' && n === '/') {
      mode = 'line'
      i++
      continue
    }
    if (c === '/' && n === '*') {
      mode = 'block'
      i++
      continue
    }
    if (c === '\'') {
      mode = 's'
      continue
    }
    if (c === '"') {
      mode = 'd'
      continue
    }
    if (c === '`') {
      mode = 't'
      continue
    }
    if (c === '{') {
      if (depth === 0) open = i
      depth++
      continue
    }
    if (c === '}') {
      depth--
      if (depth === 0 && open !== -1) return { open, close: i, key: key.index }
    }
  }
  return null
}

function hasTopLevelIcons(body) {
  let mode = 'code'
  let depth = 0
  for (let i = 0; i < body.length; i++) {
    const c = body[i]
    const n = body[i + 1]
    if (mode === 'line') {
      if (c === '\n') mode = 'code'
      continue
    }
    if (mode === 'block') {
      if (c === '*' && n === '/') {
        mode = 'code'
        i++
      }
      continue
    }
    if (mode === 's' || mode === 'd' || mode === 't') {
      const q = mode === 's' ? '\'' : mode === 'd' ? '"' : '`'
      if (c === '\\') {
        i++
        continue
      }
      if (c === q) mode = 'code'
      continue
    }
    if (c === '/' && n === '/') {
      mode = 'line'
      i++
      continue
    }
    if (c === '/' && n === '*') {
      mode = 'block'
      i++
      continue
    }
    if (c === '\'') {
      mode = 's'
      continue
    }
    if (c === '"') {
      mode = 'd'
      continue
    }
    if (c === '`') {
      mode = 't'
      continue
    }
    if (c === '{') {
      depth++
      continue
    }
    if (c === '}') {
      depth--
      continue
    }
    const prev = i === 0 ? '' : body[i - 1]
    if (depth === 0 && !/[\w$]/.test(prev) && /^icons\s*:/.test(body.slice(i))) return true
  }
  return false
}

// Inserts nativeBridge.icons when the block has no live icons key.
// A commented nnb:icons region is replaced only once a real logo is given.
export function renderIconsPatch(configText, opts = {}) {
  const span = findNativeBridge(configText)
  if (!span) return configText
  const body = configText.slice(span.open + 1, span.close)
  if (hasTopLevelIcons(body)) return configText
  const keyLine = configText.lastIndexOf('\n', span.key) + 1
  const base = (/^[ \t]*/.exec(configText.slice(keyLine)) || [''])[0]
  const snippet = renderIconsLines(`${base}  `, opts)
  const begin = body.indexOf('// nnb:icons')
  const end = body.indexOf('// /nnb:icons')
  if (begin !== -1 && end > begin) {
    if (!opts.logo) return configText
    const absBegin = span.open + 1 + begin
    const absEnd = span.open + 1 + end
    const regionStart = configText.lastIndexOf('\n', absBegin) + 1
    const endNl = configText.indexOf('\n', absEnd)
    const regionEnd = endNl === -1 ? configText.length : endNl + 1
    return configText.slice(0, regionStart) + snippet + configText.slice(regionEnd)
  }
  const insertAt = configText.lastIndexOf('\n', span.close) + 1
  return configText.slice(0, insertAt) + snippet + configText.slice(insertAt)
}

// Inserts the nativeBridge block (and the module registration) into
// nuxt.config.ts text. Existing nativeBridge blocks are left untouched;
// renderIconsPatch fills in icons on those.
export function renderNuxtConfigPatch(configText, { id, name, logo = null, brand = '#0D8A8F', commentedPath = null } = {}) {
  if (/nativeBridge:/.test(configText)) return configText

  const color = hexColor(brand)
  const icons = renderIconsLines('    ', { logo, brand: color, commentedPath }).replace(/\n$/, '')
  const block = `  // nnb:init — generated by nnb init; edit freely. If you add your own
  // modules array, merge 'nuxt-native-bridge' into it.
  nativeBridge: {
    app: { id: '${id}', name: '${name}' },
    brand: { color: '${color}' },
${icons}
    android: {
      splash: { hideOn: 'mounted', fade: 300, failsafe: 8000, light: '#0D8A8F', dark: '#0B1416' },
      mavenMirrors: ['https://maven.aliyun.com/repository/google', 'https://maven.aliyun.com/repository/central'],
      permissions: [],
    },
  },
  // /nnb:init`

  let out = configText
  // Existing modules array: append the module there (last-key-wins would
  // otherwise drop the app's own modules). Without one, the block brings it.
  const modules = /(modules:\s*\[)([^\]]*)(\])/.exec(out)
  if (modules) {
    const entries = modules[2].trim().replace(/,\s*$/, '')
    const joined = entries ? `${entries}, 'nuxt-native-bridge'` : `'nuxt-native-bridge'`
    out = out.replace(modules[0], `${modules[1]}${joined}${modules[3]}`)
  }
  // Insert before the final closer of defineNuxtConfig({ ... }).
  const closer = out.lastIndexOf('})')
  if (closer === -1) {
    throw new Error('could not find the defineNuxtConfig({...}) closer in nuxt.config.ts — wire nativeBridge manually')
  }
  const insert = modules ? block : `  modules: ['nuxt-native-bridge'],\n${block}\n`
  out = out.slice(0, closer) + `${insert}\n` + out.slice(closer)
  return out
}

