test('renderMainActivity is thin and extends the bridge activity', () => {
  const out = renderMainActivity('com.example.hello')
  assert.match(out, /^package com\.example\.hello;/m)
  assert.match(out, /extends NnbBridgeActivity/)
  assert.doesNotMatch(out, /registerPlugin/)
})

test('renderMainActivityPatch swaps the stock base class and keeps app code', () => {
  const stock = `package com.example.hello;

import com.getcapacitor.BridgeActivity;

public class MainActivity extends BridgeActivity {}
`
  const out = renderMainActivityPatch(stock)
  assert.match(out, /import com\.nnb\.bridge\.NnbBridgeActivity;/)
  assert.match(out, /extends NnbBridgeActivity/)
  assert.doesNotMatch(out, /com\.getcapacitor\.BridgeActivity/)
  assert.equal(renderMainActivityPatch(out), out)

  const appCode = `package com.example.hello;

import com.getcapacitor.BridgeActivity;

public class MainActivity extends BridgeActivity {
  @Override
  public void onCreate(android.os.Bundle b) {
    registerPlugin(ThemePrefsPlugin.class);
    super.onCreate(b);
  }
}
`
  assert.match(renderMainActivityPatch(appCode), /registerPlugin\(ThemePrefsPlugin\.class\)/)
  assert.equal(renderMainActivityPatch('public class MainActivity extends CustomActivity {}'), null)
})

test('wireAndroid repairs an existing stock shell and is idempotent', (t) => {
  const appDir = fs.mkdtempSync(path.join(os.tmpdir(), 'nnb-wire-'))
  t.after(() => fs.rmSync(appDir, { recursive: true, force: true }))
  const android = path.join(appDir, 'android')
  const javaDir = path.join(android, 'app', 'src', 'main', 'java', 'com', 'example', 'hello')
  fs.mkdirSync(javaDir, { recursive: true })
  const main = path.join(javaDir, 'MainActivity.java')
  fs.writeFileSync(main, `package com.example.hello;

import com.getcapacitor.BridgeActivity;

public class MainActivity extends BridgeActivity {}
`)
  const settings = path.join(android, 'settings.gradle')
  fs.writeFileSync(settings, 'include \':app\'\n')
  const appGradle = path.join(android, 'app', 'build.gradle')
  fs.writeFileSync(appGradle, 'dependencies {\n    implementation project(\':capacitor-android\')\n}\n')
  const variables = path.join(android, 'variables.gradle')
  fs.writeFileSync(variables, 'ext {\n    compileSdkVersion = 36\n}\n')
  const wrapperDir = path.join(android, 'gradle', 'wrapper')
  fs.mkdirSync(wrapperDir, { recursive: true })
  const wrapper = path.join(wrapperDir, 'gradle-wrapper.properties')
  fs.writeFileSync(wrapper, 'distributionUrl=https\\://services.gradle.org/distributions/gradle-8.14.3-all.zip\n')

  assert.equal(wireAndroid(appDir, 'com.example.hello'), true)

  assert.ok(fs.existsSync(path.join(android, 'nnb-bridge', 'build.gradle')))
  assert.ok(fs.existsSync(path.join(android, 'app', 'src', 'main', 'assets')))
  assert.match(fs.readFileSync(main, 'utf8'), /extends NnbBridgeActivity/)
  assert.match(fs.readFileSync(settings, 'utf8'), /include ':nnb-bridge'/)
  assert.match(fs.readFileSync(appGradle, 'utf8'), /implementation project\(':nnb-bridge'\)/)
  assert.match(fs.readFileSync(variables, 'utf8'), /buildToolsVersion = '36\.0\.0'/)
  assert.match(fs.readFileSync(wrapper, 'utf8'), /mirrors\.cloud\.tencent\.com/)

  const files = [main, settings, appGradle, variables, wrapper]
  const snapshot = files.map(f => fs.readFileSync(f, 'utf8'))
  wireAndroid(appDir, 'com.example.hello')
  assert.deepEqual(files.map(f => fs.readFileSync(f, 'utf8')), snapshot)
  assert.equal((fs.readFileSync(settings, 'utf8').match(/:nnb-bridge/g) || []).length, 2)
})

const SETTINGS = `dependencyResolutionManagement {
    repositories {
        google()
        mavenCentral()
    }
}

include ':app'
`

test('renderBridgeInclude inserts markers with the computed relative path', () => {
  const out = renderBridgeInclude(SETTINGS, '../../packages/adapter-capacitor/android')
  assert.match(out, /nnb:bridge-library[\s\S]*include ':nnb-bridge'[\s\S]*projectDir = new File\('\.\.\/\.\.\/packages\/adapter-capacitor\/android'\)/)
  // before include ':app', gradle-comment markers
  assert.match(out, /\/nnb:bridge-library\n\ninclude ':app'/)
})

test('renderBridgeInclude is idempotent', () => {
  const once = renderBridgeInclude(SETTINGS, '../../packages/adapter-capacitor/android')
  const twice = renderBridgeInclude(once, '../../packages/adapter-capacitor/android')
  assert.equal(twice, once)
})

test('renderBuildToolsPin pins the pair next to compileSdk, idempotent', () => {
  const vars = `ext {\n    minSdkVersion = 24\n    compileSdkVersion = 36\n    targetSdkVersion = 36\n}\n`
  const varsOut = renderBuildToolsPin(vars)
  assert.match(varsOut, /compileSdkVersion = 36\n {4}buildToolsVersion = '36\.0\.0'/)
  assert.equal(renderBuildToolsPin(varsOut), varsOut)
  // pre-pinned files pass through untouched
  const pinned = `ext {\n    buildToolsVersion = '34.0.0'\n}\n`
  assert.equal(renderBuildToolsPin(pinned), pinned)
})

const WITH_BRIDGE = `export default defineNuxtConfig({
  nativeBridge: {
    app: { id: 'com.example.askmed', name: 'askmed' },
    brand: { color: '#112233' },
    android: {
      icons: { foreground: 'assets/icons/app_icon.png' },
    },
  },
})
`

test('normalizeLogoPath keeps a relative path and rejects escapes', () => {
  assert.deepEqual(normalizeLogoPath('public\\logo.png'), { path: 'public/logo.png' })
  assert.deepEqual(normalizeLogoPath('./public/logo.png'), { path: 'public/logo.png' })
  assert.ok(normalizeLogoPath('../secret.png').error)
  assert.ok(normalizeLogoPath('/etc/passwd').error)
  assert.ok(normalizeLogoPath('public/logo.png\'').error)
})

test('resolveLogo accepts a real file and keeps a missing path commented', () => {
  const appDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
  assert.equal(resolveLogo(appDir, 'package.json').logo, 'package.json')
  const missing = resolveLogo(appDir, 'public/no-such-logo.png')
  assert.equal(missing.logo, null)
  assert.equal(missing.commentedPath, 'public/no-such-logo.png')
})

test('renderIconsPatch inserts a commented example and leaves a live block alone', () => {
  const commented = renderIconsPatch(WITH_BRIDGE, { brand: '#112233' })
  assert.match(commented, /\/\/ nnb:icons — point source/)
  assert.match(commented, /\/\/ {3}source: 'public\/logo\.png'/)
  assert.match(commented, /android: \{\n {6}icons: \{ foreground: 'assets\/icons\/app_icon\.png' \}/)
  assert.equal(renderIconsPatch(commented, { brand: '#112233' }), commented)

  const live = renderIconsPatch(commented, { logo: 'public/logo/logo-web.png', brand: '#112233' })
  assert.match(live, /\n {4}icons: \{\n {6}source: 'public\/logo\/logo-web\.png',\n {6}android: \{ glyph: 'public\/logo\/logo-web\.png', background: '#112233' \},\n {6}splash: 'public\/logo\/logo-web\.png',\n {4}\},/)
  assert.doesNotMatch(live, /\/\/ icons:/)
  assert.equal(renderIconsPatch(live, { logo: 'public/other.png', brand: '#112233' }), live)
})

test('renderNuxtConfigPatch writes a live icons block when a logo is given', () => {
  const out = renderNuxtConfigPatch(NUXT_CONFIG, { id: 'com.example.hello', name: 'Hello', logo: 'public/logo.png', brand: '#112233' })
  assert.match(out, /brand: \{ color: '#112233' \}/)
  assert.match(out, /source: 'public\/logo\.png'/)
  assert.doesNotMatch(out, /\/\/ icons:/)
})

test('renderWrapperMirror swaps only the gradle-dist host', () => {
  const props = 'distributionUrl=https\\://services.gradle.org/distributions/gradle-8.14.3-all.zip\nnetworkTimeout=10000\n'
  const out = renderWrapperMirror(props)
  assert.match(out, /^distributionUrl=https:\/\/mirrors\.cloud\.tencent\.com\/gradle\/gradle-8\.14\.3-all\.zip$/m)
  assert.match(out, /^networkTimeout=10000$/m)
  // unescaped input and idempotency
  assert.equal(renderWrapperMirror('distributionUrl=https://services.gradle.org/distributions/gradle-9.0-all.zip\n'),
    'distributionUrl=https://mirrors.cloud.tencent.com/gradle/gradle-9.0-all.zip\n')
  assert.equal(renderWrapperMirror(out), out)
})
