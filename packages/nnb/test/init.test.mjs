const NUXT_CONFIG = `export default defineNuxtConfig({
  compatibilityDate: '2025-01-01',
  devtools: { enabled: true },
})
`

test('renderNuxtConfigPatch inserts the marker block and the modules entry', () => {
  const out = renderNuxtConfigPatch(NUXT_CONFIG, { id: 'com.example.hello', name: 'Hello' })
  assert.match(out, /nnb:init[\s\S]*nativeBridge:[\s\S]*app: \{ id: 'com\.example\.hello', name: 'Hello' \}/)
  assert.match(out, /theme: 'both'/)
  assert.match(out, /modules: \['nuxt-native-bridge'\]/)
  assert.match(out, /\/\/ nnb:icons — point source, glyph and splash at your logo/)
  assert.match(out, /\/\/ icons: \{\n {4}\/\/ {3}source: 'public\/logo\.png'/)
  // inserted inside defineNuxtConfig — the final closer is untouched
  assert.equal((out.match(/\}\)/g) || []).length, 1)
})

test('renderNuxtConfigPatch appends to an existing modules array', () => {
  const withModules = NUXT_CONFIG.replace(
    '  compatibilityDate',
    '  modules: [\'@nuxt/eslint\'],\n  compatibilityDate',
  )
  const out = renderNuxtConfigPatch(withModules, { id: 'com.example.hello', name: 'Hello' })
  assert.match(out, /modules: \['@nuxt\/eslint', 'nuxt-native-bridge'\]/)
  // and the module name is not duplicated into the marker block
  assert.doesNotMatch(out, /modules: \['nuxt-native-bridge'\]/)
})

test('renderNuxtConfigPatch puts nnb before @nuxt/image', () => {
  const withModules = NUXT_CONFIG.replace(
    '  compatibilityDate',
    '  modules: [\'@nuxt/eslint\', \'@nuxt/image\'],\n  compatibilityDate',
  )
  const out = renderNuxtConfigPatch(withModules, { id: 'com.example.hello', name: 'Hello' })
  assert.match(out, /modules: \['nuxt-native-bridge', '@nuxt\/eslint', '@nuxt\/image'\]/)
})

test('renderNuxtConfigPatch is idempotent and registers the module on an existing block', () => {
  const once = renderNuxtConfigPatch(NUXT_CONFIG, { id: 'com.example.hello', name: 'Hello' })
  const twice = renderNuxtConfigPatch(once, { id: 'com.example.hello', name: 'Hello' })
  assert.equal(twice, once)
})

test('renderModuleRegistration registers the module on an existing nativeBridge config', () => {
  // derma's shape: the block and the marker comment exist, the modules entry
  // does not. The comment mentions the module name, which must not count.
  const existing = `export default defineNuxtConfig({
  modules: ["@nuxt/icon", "@nuxt/image"],
  compatibilityDate: '2025-12-29',
  // nnb:init — generated by nnb init; edit freely. If you add your own
  // modules array, merge 'nuxt-native-bridge' into it.
  nativeBridge: {
    app: { id: 'com.example.hello', name: 'Hello' },
  },
  // /nnb:init
})
`
  const out = renderModuleRegistration(existing)
  assert.match(out, /modules: \['nuxt-native-bridge', "@nuxt\/icon", "@nuxt\/image"\]/)
  assert.equal(renderModuleRegistration(out), out)
  assert.match(renderNuxtConfigPatch(existing, { id: 'com.example.hello', name: 'Hello' }), /'nuxt-native-bridge'/)
})

test('wireNuxtConfig registers the module in an existing config and is idempotent', (t) => {
  const appDir = fs.mkdtempSync(path.join(os.tmpdir(), 'nnb-config-'))
  t.after(() => fs.rmSync(appDir, { recursive: true, force: true }))
  const file = path.join(appDir, 'nuxt.config.ts')
  fs.writeFileSync(file, NUXT_CONFIG.replace('compatibilityDate', 'nativeBridge: {},\n  compatibilityDate'))

  assert.equal(wireNuxtConfig(appDir), true)
  assert.match(fs.readFileSync(file, 'utf8'), /modules: \['nuxt-native-bridge'\]/)
  assert.equal(wireNuxtConfig(appDir), false)
})

